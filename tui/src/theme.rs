//! Colour themes.
//!
//! Every colour the UI draws comes from here, so a theme is a pure data change —
//! no renderer edits, and no theme can leave part of the screen unstyled.
//!
//! Colours are 24-bit RGB. Terminals that only do 256 colours degrade them
//! automatically; `terminal` is the one theme that deliberately uses the
//! terminal's own ANSI palette instead, so it inherits whatever scheme the user
//! has configured in their emulator.

use ratatui::style::Color;

#[derive(Clone)]
pub struct Theme {
    pub name: &'static str,
    pub bg: Color,
    pub fg: Color,
    /// Timestamps, status lines, inactive list entries.
    pub dim: Color,
    pub border: Color,
    /// Selection background (buffer list, topic bar).
    pub accent: Color,
    /// Text drawn ON `accent`.
    pub accent_fg: Color,
    pub status_bg: Color,
    pub status_fg: Color,
    /// Mentions and highlight activity.
    pub highlight: Color,
    /// Our own messages.
    pub own: Color,
    pub notice: Color,
    pub action: Color,
    pub error: Color,
    /// Connected/disconnected dots in the buffer list.
    pub online: Color,
    /// Deterministic per-nick colours. Kept separate from the semantic colours so
    /// a theme can be tuned for readability without disturbing nick identity.
    pub nicks: [Color; 8],
}

const fn c(r: u8, g: u8, b: u8) -> Color { Color::Rgb(r, g, b) }

/// Build a theme from a compact palette. The nick set is the six accent hues plus
/// two derived, which keeps each theme's nicks inside its own palette rather than
/// dropping a generic rainbow onto every scheme.
const fn t(
    name: &'static str,
    bg: (u8, u8, u8), fg: (u8, u8, u8), dim: (u8, u8, u8), border: (u8, u8, u8),
    accent: (u8, u8, u8), accent_fg: (u8, u8, u8),
    red: (u8, u8, u8), green: (u8, u8, u8), yellow: (u8, u8, u8),
    blue: (u8, u8, u8), magenta: (u8, u8, u8), cyan: (u8, u8, u8),
) -> Theme {
    Theme {
        name,
        bg: c(bg.0, bg.1, bg.2),
        fg: c(fg.0, fg.1, fg.2),
        dim: c(dim.0, dim.1, dim.2),
        border: c(border.0, border.1, border.2),
        accent: c(accent.0, accent.1, accent.2),
        accent_fg: c(accent_fg.0, accent_fg.1, accent_fg.2),
        status_bg: c(accent.0, accent.1, accent.2),
        status_fg: c(accent_fg.0, accent_fg.1, accent_fg.2),
        highlight: c(magenta.0, magenta.1, magenta.2),
        own: c(fg.0, fg.1, fg.2),
        notice: c(red.0, red.1, red.2),
        action: c(magenta.0, magenta.1, magenta.2),
        error: c(red.0, red.1, red.2),
        online: c(green.0, green.1, green.2),
        nicks: [
            c(cyan.0, cyan.1, cyan.2), c(green.0, green.1, green.2),
            c(yellow.0, yellow.1, yellow.2), c(blue.0, blue.1, blue.2),
            c(magenta.0, magenta.1, magenta.2), c(red.0, red.1, red.2),
            c(accent.0, accent.1, accent.2), c(fg.0, fg.1, fg.2),
        ],
    }
}

/// The one theme that uses the terminal's OWN palette rather than fixed RGB, so
/// it follows whatever scheme the user has set in their emulator.
fn terminal_theme() -> Theme {
    Theme {
        name: "terminal",
        bg: Color::Reset, fg: Color::Reset, dim: Color::DarkGray, border: Color::DarkGray,
        accent: Color::Cyan, accent_fg: Color::Black,
        status_bg: Color::Cyan, status_fg: Color::Black,
        // `own` stays Reset: this theme exists to follow the user's palette, and
        // an absolute White renders invisibly on a light-background terminal.
        // BOLD is what actually distinguishes our own messages.
        highlight: Color::LightMagenta, own: Color::Reset,
        notice: Color::LightRed, action: Color::Magenta, error: Color::Red,
        online: Color::Green,
        nicks: [Color::Cyan, Color::Green, Color::Yellow, Color::Blue,
                Color::Magenta, Color::LightCyan, Color::LightGreen, Color::LightBlue],
    }
}

/// Relative luminance (WCAG). Only meaningful for concrete RGB.
fn lum(c: Color) -> Option<f32> {
    let Color::Rgb(r, g, b) = c else { return None };
    fn ch(v: u8) -> f32 {
        let v = v as f32 / 255.0;
        if v <= 0.03928 { v / 12.92 } else { ((v + 0.055) / 1.055).powf(2.4) }
    }
    Some(0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b))
}

fn contrast(a: Color, b: Color) -> Option<f32> {
    let (la, lb) = (lum(a)?, lum(b)?);
    let (hi, lo) = if la > lb { (la, lb) } else { (lb, la) };
    Some((hi + 0.05) / (lo + 0.05))
}

/// `dim` carries every timestamp, join/part/quit and inactive buffer name — a
/// large share of the screen. Several upstream schemes use a comment colour that
/// measures below 3:1 against their own background (nord 1.69, base16-light 1.87,
/// one-dark 2.32 …), which is genuinely hard to read. Rather than hand-editing
/// palettes, lift `dim` toward `fg` until it clears the floor. Themes already
/// above it are untouched, and this automatically covers any theme added later.
fn enforce_dim_contrast(t: &mut Theme) {
    const FLOOR: f32 = 3.0;
    let (Color::Rgb(dr, dg, db), Color::Rgb(fr, fg_, fb)) = (t.dim, t.fg) else { return };
    for step in 1..=10 {
        match contrast(t.dim, t.bg) {
            Some(c) if c >= FLOOR => return,
            None => return,
            _ => {}
        }
        let k = step as f32 / 10.0;
        let mix = |d: u8, f: u8| (d as f32 + (f as f32 - d as f32) * k).round() as u8;
        t.dim = c(mix(dr, fr), mix(dg, fg_), mix(db, fb));
    }
}

pub fn all() -> Vec<Theme> {
    let mut v = vec![terminal_theme()];
    v.extend(FIXED.iter().cloned());
    for t in v.iter_mut() { enforce_dim_contrast(t); }
    v
}

pub fn get(name: &str) -> Option<Theme> {
    all().into_iter().find(|t| t.name.eq_ignore_ascii_case(name))
}

pub fn names() -> Vec<&'static str> { all().iter().map(|t| t.name).collect() }

pub fn default_theme() -> Theme { get("gruvbox-dark").unwrap_or_else(terminal_theme) }

